-- V1: tabelas da Receita de Voinha.
-- O mesmo SQL roda no PostgreSQL (Supabase) e no H2 (modo PostgreSQL).
-- O Flyway executa no schema "voinha" (spring.flyway.default-schema).

CREATE TABLE categorias (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(50) NOT NULL UNIQUE,
    icone VARCHAR(16)
);

CREATE TABLE usuarios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(80) NOT NULL,
    login      VARCHAR(40) NOT NULL UNIQUE,
    senha_hash VARCHAR(72) NOT NULL -- hash BCrypt, nunca a senha
);

CREATE TABLE receitas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo       VARCHAR(100)  NOT NULL,
    descricao    VARCHAR(1000) NOT NULL,
    imagem       VARCHAR(255),
    nota         FLOAT(53)     NOT NULL,
    tempo        VARCHAR(20)   NOT NULL,
    categoria_id BIGINT NOT NULL REFERENCES categorias (id),
    autor_id     BIGINT REFERENCES usuarios (id)
);

-- Listas ordenadas da receita (@ElementCollection + @OrderColumn "posicao")
CREATE TABLE receita_ingredientes (
    receita_id  BIGINT       NOT NULL REFERENCES receitas (id) ON DELETE CASCADE,
    posicao     INTEGER      NOT NULL,
    ingrediente VARCHAR(255) NOT NULL,
    PRIMARY KEY (receita_id, posicao)
);

CREATE TABLE receita_preparo (
    receita_id BIGINT        NOT NULL REFERENCES receitas (id) ON DELETE CASCADE,
    posicao    INTEGER       NOT NULL,
    passo      VARCHAR(1000) NOT NULL,
    PRIMARY KEY (receita_id, posicao)
);

-- Favoritos de cada usuário (@ManyToMany em Usuario)
CREATE TABLE usuario_favoritos (
    usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    receita_id BIGINT NOT NULL REFERENCES receitas (id) ON DELETE CASCADE,
    PRIMARY KEY (usuario_id, receita_id)
);

CREATE INDEX idx_receitas_categoria ON receitas (categoria_id);
CREATE INDEX idx_receitas_autor ON receitas (autor_id);
CREATE INDEX idx_favoritos_receita ON usuario_favoritos (receita_id);
